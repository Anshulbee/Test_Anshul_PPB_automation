package org.example;

import com.github.tomakehurst.wiremock.WireMockServer;
import com.github.tomakehurst.wiremock.client.WireMock;
import io.restassured.response.Response;
import org.example.utils.API_XmlUtil;
import org.example.utils.PropertyUtil;

import java.io.IOException;

import static com.github.tomakehurst.wiremock.client.WireMock.*;
import static io.restassured.RestAssured.given;

public class post_API_wireMock {

    // Class fields
    protected String responseBody;
    private WireMockServer wireMockServer;
    private final int MOCK_PORT = 8081;

    public post_API_wireMock(String apiurl, String xml_name, String xml_prop) throws IOException {

        String baseUrl = "http://localhost:" + MOCK_PORT;
        System.out.println("Base URL: " + baseUrl);

        String contentType = String.valueOf(PropertyUtil.getProperty("content.type"));
        System.out.println("Content Type:: " + contentType);

        String xmlPath = String.valueOf(PropertyUtil.getProperty(xml_name));
        String requestBody = API_XmlUtil.loadXmlAsString(xmlPath);

        // 1. Initialize and start the local WireMock server
        wireMockServer = new WireMockServer(MOCK_PORT);
        wireMockServer.start();
        WireMock.configureFor("localhost", MOCK_PORT);

        // 2. Define fixed response payload
        String exactResponsePayload = "<FIXML xmlns=\"http://infosys.com\">\n" +
                "  <Header>\n" +
                "    <ResponseHeader>\n" +
                "      <RequestMessageKey>\n" +
                "        <RequestMessageId>REQ_NEFT_2026101401</RequestMessageId>\n" +
                "      </RequestMessageKey>\n" +
                "      <ResponseMessageInfo>\n" +
                "        <ResponseMessageId>RES_NEFT_9876543210</ResponseMessageId>\n" +
                "        <ResponseMessageDt>2026-10-14T23:15:00.000</ResponseMessageDt>\n" +
                "      </ResponseMessageInfo>\n" +
                "      <Status>\n" +
                "        <StatusCode>SUCCESS</StatusCode>\n" +
                "        <Severity>INFO</Severity>\n" +
                "      </Status>\n" +
                "    </ResponseHeader>\n" +
                "  </Header>\n" +
                "  <Body>\n" +
                "    <pmtAddResponse>\n" +
                "      <pmtAddCustomData />\n" +
                "      <PaymentOrderDetails>\n" +
                "        <!-- The internal Finacle Payment Order ID generated by HPORDM -->\n" +
                "        <paymentOrderId>PO102938475</paymentOrderId>\n" +
                "        <!-- The system assigned Unique Transaction Reference (UTR) for NEFT tracking -->\n" +
                "        <utrNo>BARBN26288123456</utrNo> \n" +
                "        <txnStatus>E</txnStatus> <!-- E = Entered, R = Ready for transmission -->\n" +
                "        <amountDetails>\n" +
                "          <amount ccy=\"INR\">25000.00</amount>\n" +
                "          <chargeAmount ccy=\"INR\">2.50</chargeAmount>\n" +
                "          <gstAmount ccy=\"INR\">0.45</gstAmount>\n" +
                "        </amountDetails>\n" +
                "        <executionDt>2026-10-14T00:00:00.000</executionDt>\n" +
                "      </PaymentOrderDetails>\n" +
                "    </pmtAddResponse>\n" +
                "  </Body>\n" +
                "</FIXML>";
        // 3. Optimized Stub Mapping (Matches URL exactly, ignores volatile body string variations)
        WireMock.stubFor(WireMock.post(WireMock.urlPathEqualTo("/"+xml_name))
                .withHeader("Content-Type", WireMock.containing(contentType)) // 'containing' safe-checks text boundaries
                .willReturn(WireMock.aResponse()
                        .withStatus(200)
                        .withHeader("Content-Type", contentType)
                        .withBody(exactResponsePayload)));

        // 4. REST API POST request execution
        Response restAssuredResponse = given()
                .baseUri(baseUrl)
                .header("Content-Type",contentType)
                .body(requestBody)
                .when()
                .post("/"+xml_name)
                .then()
                .statusCode(200)
                .header("Content-Type",contentType)
                .extract()
                .response();

        // 5. Store data to global variable safely (Fixed Shadow Bug)
        this.responseBody = restAssuredResponse.asString();
        System.out.println("XML Response Body:\n" + this.responseBody);

        // 6. Stop server down here if this constructor handles self-contained runs
        stopMockServer();
    }

    public String getResponseBody() {
        return this.responseBody;
    }

    public void stopMockServer() {
        if (wireMockServer != null && wireMockServer.isRunning()) {
            wireMockServer.stop();
        }
    }
}
